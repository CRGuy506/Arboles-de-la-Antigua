const root = document.documentElement;
const body = document.body;
const langTrigger = document.getElementById("langTrigger");
const langMenu = document.getElementById("langMenu");
const langCurrentLabel = document.getElementById("langCurrentLabel");
const langCurrentFlag = document.getElementById("langCurrentFlag");
const themeToggle = document.getElementById("themeToggle");

const languageNames = {
  es: "Español (ES)",
  en: "English (EN)",
  fr: "Français (FR)"
};

function ensureLanguageOption(langCode, label, flagClass) {
  if (!langMenu) {
    return;
  }
  const selector = `.lang-option[data-lang="${langCode}"]`;
  if (langMenu.querySelector(selector)) {
    return;
  }

  const option = document.createElement("button");
  option.type = "button";
  option.className = "lang-option";
  option.setAttribute("data-lang", langCode);
  option.setAttribute("role", "option");
  option.innerHTML = `<span class="flag ${flagClass}" aria-hidden="true"></span><span>${label}</span>`;
  langMenu.appendChild(option);
}

function setThemeToggleText(lang, theme) {
  if (!themeToggle) {
    return;
  }
  const nextTheme = theme === "dark" ? "light" : "dark";
  const label = nextTheme === "dark" ? translations[lang].dark : translations[lang].light;
  themeToggle.setAttribute("aria-label", label);
  themeToggle.setAttribute("title", label);
}

function updateLanguageUI(lang) {
  if (langCurrentLabel) {
    langCurrentLabel.textContent = lang.toUpperCase();
  }
  if (langCurrentFlag) {
    langCurrentFlag.className = `flag flag-${lang}`;
  }
  if (langTrigger) {
    langTrigger.setAttribute("aria-label", languageNames[lang] || lang.toUpperCase());
  }
  if (langMenu) {
    langMenu.querySelectorAll(".lang-option[data-lang]").forEach((option) => {
      const optionLang = option.getAttribute("data-lang");
      option.setAttribute("aria-selected", optionLang === lang ? "true" : "false");
    });
  }
}

function closeLanguageMenu() {
  if (langMenu) {
    langMenu.hidden = true;
  }
  if (langTrigger) {
    langTrigger.setAttribute("aria-expanded", "false");
  }
}

function setupLanguageDropdown() {
  if (!langTrigger || !langMenu) {
    return;
  }

  ensureLanguageOption("es", "Español (ES)", "flag-es");
  ensureLanguageOption("en", "English (EN)", "flag-en");
  ensureLanguageOption("fr", "Français (FR)", "flag-fr");

  langTrigger.addEventListener("click", () => {
    const nextOpen = langMenu.hidden;
    langMenu.hidden = !nextOpen;
    langTrigger.setAttribute("aria-expanded", String(nextOpen));
  });

  langMenu.querySelectorAll(".lang-option[data-lang]").forEach((option) => {
    option.addEventListener("click", () => {
      const selectedLang = option.getAttribute("data-lang");
      if (selectedLang && translations[selectedLang]) {
        applyLanguage(selectedLang);
      }
      closeLanguageMenu();
    });
  });

  document.addEventListener("click", (event) => {
    const target = event.target;
    if (!(target instanceof Node)) {
      return;
    }
    if (!langTrigger.contains(target) && !langMenu.contains(target)) {
      closeLanguageMenu();
    }
  });
}

function setupTabTransitions() {
  if (!body) {
    return;
  }

  const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

  // Entry state for smoother first paint on each tab page.
  if (!reduceMotion) {
    body.classList.add("page-enter");
    window.requestAnimationFrame(() => {
      body.classList.add("page-enter-active");
      window.setTimeout(() => {
        body.classList.remove("page-enter", "page-enter-active");
      }, 260);
    });
  }

  const navLinks = document.querySelectorAll(".main-nav a[href]");
  navLinks.forEach((link) => {
    link.addEventListener("click", (event) => {
      const href = link.getAttribute("href");
      if (!href || reduceMotion) {
        return;
      }

      // Let new-tab/open-in-new-window behavior work normally.
      if (event.metaKey || event.ctrlKey || event.shiftKey || event.altKey || event.button !== 0) {
        return;
      }

      const targetUrl = new URL(href, window.location.href);
      if (targetUrl.origin !== window.location.origin || targetUrl.pathname === window.location.pathname) {
        return;
      }

      event.preventDefault();
      body.classList.add("page-exit");
      window.setTimeout(() => {
        window.location.href = targetUrl.href;
      }, 190);
    });
  });
}

function markActiveNavLink() {
  const currentPath = window.location.pathname.split("/").pop() || "home.html";
  document.querySelectorAll(".main-nav a[data-nav-key]").forEach((link) => {
    const href = link.getAttribute("href");
    link.classList.toggle("active", href === currentPath);
  });
}

